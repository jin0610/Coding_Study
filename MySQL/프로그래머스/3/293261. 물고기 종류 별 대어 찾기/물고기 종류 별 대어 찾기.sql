SELECT A.ID, B.FISH_NAME, B.LENGTH
FROM FISH_INFO A 
JOIN (
    SELECT I.ID, N.FISH_TYPE, N.FISH_NAME AS FISH_NAME, MAX(I.LENGTH) AS LENGTH
    FROM FISH_INFO I JOIN FISH_NAME_INFO N
    ON I.FISH_TYPE = N.FISH_TYPE
    GROUP BY I.FISH_TYPE
    ORDER BY I.ID
) B
ON A.FISH_TYPE = B.FISH_TYPE AND A.LENGTH = B.LENGTH
ORDER BY A.ID
