WITH COUNT_REVIEW AS (
    SELECT MEMBER_ID, COUNT(*) AS REVIEW
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
)

SELECT P.MEMBER_NAME, R.REVIEW_TEXT,  REVIEW_DATE
FROM MEMBER_PROFILE P INNER JOIN REST_REVIEW R ON P.MEMBER_ID = R.MEMBER_ID
WHERE P.MEMBER_ID IN (
                    SELECT MEMBER_ID FROM COUNT_REVIEW 
                    WHERE REVIEW = (SELECT MAX(REVIEW) FROM COUNT_REVIEW)
                    )
ORDER BY REVIEW_DATE, REVIEW_TEXT
